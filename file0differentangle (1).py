def tokenized_data(entries, tokenizer):
  print("tokenize data")
  s1_tok = []
  s2_tok = []

  #https://www.w3schools.com/python/pandas/ref_df_iterrows.asp
  for i, entry in entries.iterrows():
    s1_tok.append(tokenizer.encode(entry['sentence1'], return_tensors = "tf"))
    s2_tok.append(tokenizer.encode(entry['sentence2'], return_tensors = "tf"))

  entries['s1_tok'] = s1_tok
  entries['s2_tok'] = s2_tok

  print(entries)

