def find_removals(entries, to_remove):
  print("finding sentences to remove")
  #https://pandas.pydata.org/docs/reference/api/pandas.DataFrame.drop.html we can drop rows via axis=0

  #for eeach row of s1, gonna have to make a copy, flatten the copy,
  #search it for matching tokens, note row nums, then use row nums to drop from original panda df
  s1_tok = entries["s1_tok"]
  print(type(s1_tok))
  print(s1_tok)

  def flattening_to_tok(s1_tok):
    print("flattening copy of s1")
    s1_flat = []
    for entry in s1_tok:
      s1_flat.append(s1_tok.to_numpy().flatten().tolist())
    return s1_flat

  def finder(s1_flat, to_remove):

    def word_search(entry, to_remove):
      sent1_has_word = False
      #10/29/25 update, adding it infrastructure for subtokens
      def contains_sequence(tokens, sequence):
        for seq in sequence:
          n = len(seq)
          for i in range(len(tokens) - n + 1):
            if tokens[i:i+n] == seq:
              return True
        return False

      sent1_has_word = contains_sequence(entry, to_remove)
      return sent1_has_word

    counter_s1 = 0
    row_tracker = []

    for i, entry in s1_flat.iterrows():
      s1_has = word_search(entry, to_remove)
      if s1_has:
        counter_s1 += 1
        #https://pandas.pydata.org/docs/reference/api/pandas.DataFrame.index.html
        #https://www.reddit.com/r/learnpython/comments/4c6bjc/getting_the_index_number_of_a_specific_row_pandas/
        #this should give me the index of any rows in the dataframe that are identified as having my desired removals
        row_tracker.append(s1_flat.index[i])

    return row_tracker, counter_s1


  def cull_data(entries, row_tracker):
    #https://pandas.pydata.org/docs/reference/api/pandas.DataFrame.iloc.html
    #use iloc to save just some indexes iloc = index location
    #better stratiegy would be to remove the rows we don't need
    #https://pandas.pydata.org/docs/reference/api/pandas.DataFrame.drop.html
    for i, entry in entries.iterrows():
      if i not in row_tracker:
        entries.drop([i])

  s1_flat = flattening_to_tok(s1_tok)
  row_tracker, counter_s1 = finder(s1_flat, to_remove)
  cull_data(entries, row_tracker)
  return counter_s1, row_tracker



